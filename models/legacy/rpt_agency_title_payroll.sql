-- AGENCY TITLE PAYROLL REPORT
-- feeds commissioner dashboard. DO NOT CHANGE w/o talking to RK
-- last updated 3/2019
SELECT
	X.AGENCY_CODE,
	X.AGENCY_NAME,
	X.AGENCY_GROUP,
	X.TITLE_CODE,
	X.TITLE_DESC,
	X.UNION_DESC,
	X.HEADCOUNT,
	X.TOTAL_ANNUAL_SALARY,
	CASE
		WHEN X.TOTAL_ANNUAL_SALARY / X.HEADCOUNT < 40000 THEN '1 - UNDER 40K'
		WHEN X.TOTAL_ANNUAL_SALARY / X.HEADCOUNT < 70000 THEN '2 - 40K-70K'
		WHEN X.TOTAL_ANNUAL_SALARY / X.HEADCOUNT <= 100000 THEN '3 - 70K-100K'
		WHEN X.TOTAL_ANNUAL_SALARY / X.HEADCOUNT >= 100000 THEN '4 - 100K+'
	END AS salary_band
FROM (
	SELECT
		B.AGENCY_CODE,
		B.AGENCY_NAME,
		B.AGENCY_GROUP,
		B.TITLE_CODE,
		B.TITLE_DESC,
		B.UNION_DESC,
		COUNT(*) AS headcount,
		ROUND(SUM(B.ANNUAL_SALARY), 2)::DECIMAL(14, 2) AS total_annual_salary
	FROM (
		SELECT
			A.*,
			-- fix truncated names for dashboard
			CASE
				WHEN A.AGENCY_NAME = 'DEPARTMENT OF CITYWIDE ADM' THEN 'DEPARTMENT OF CITYWIDE ADMINISTRATIVE SERVICES'
				WHEN A.AGENCY_NAME = 'DEPARTMENT OF PARKS & RECR' THEN 'DEPARTMENT OF PARKS & RECREATION'
				WHEN A.AGENCY_NAME = 'HRA/DEPARTMENT OF SOCIAL S' THEN 'HRA/DEPARTMENT OF SOCIAL SERVICES'
				WHEN A.AGENCY_NAME = 'DEPARTMENT OF INFORMATION' THEN 'OFFICE OF TECHNOLOGY & INNOVATION'
				ELSE A.AGENCY_NAME
			END AS agency_name,
			CASE
				WHEN A.AGENCY_CODE::INT IN (56, 57, 72, 827) THEN 'UNIFORMED'
				WHEN A.AGENCY_CODE::INT = 740 OR A.AGENCY_NAME LIKE 'CUNY%' THEN 'EDUCATION'
				WHEN A.AGENCY_CODE::INT IN (69, 71, 816) THEN 'HEALTH & HUMAN SVCS'
				WHEN A.AGENCY_CODE::INT BETWEEN 901 AND 906 THEN 'DISTRICT ATTORNEYS'
				-- WHEN A.AGENCY_CODE::INT IN (996, 998) THEN 'AUTHORITIES'  -- removed per RK
				ELSE 'OTHER'
			END AS agency_group,
			-- annualize. pay class codes from payroll mgmt system, see email from DCAS
			CASE
				WHEN A.PAY_CLASS IN ('A', 'D', 'F', 'G', 'I', 'BW', 'WK', '0', '01', '02', '03', '04') THEN A.SALARY_RATE
				WHEN A.PAY_CLASS IN ('X', 'U', 'V') THEN A.SALARY_RATE * 2080
				WHEN A.PAY_CLASS IN ('N', 'O', 'L', 'W', '2') THEN A.SALARY_RATE * A.STD_HRS * 52
				WHEN A.PAY_CLASS IN ('K', 'E') THEN A.SALARY_RATE * 261
				WHEN A.PAY_CLASS = 'S' THEN 0  -- commissioners
				ELSE A.SALARY_RATE
			END AS annual_salary
		FROM (
			SELECT
				E.*,
				T.TITLE_DESC,
				T.UNION_DESC,
				(SELECT MAX(T2.STANDARD_HOURS) FROM {{ ref("stg_civil_service_titles") }} T2 WHERE T2.TITLE_CODE = E.TITLE_CODE) AS std_hrs
			FROM {{ ref("stg_civil_servants") }} E
			-- one row per title: some titles are represented by more than one union
			JOIN (
				SELECT
					TITLE_CODE,
					ANY_VALUE(TITLE_DESC) AS title_desc,
					STRING_AGG(DISTINCT UNION_DESC, '; ' ORDER BY UNION_DESC) AS union_desc
				FROM {{ ref("stg_civil_service_titles") }}
				GROUP BY TITLE_CODE
			) T
				ON E.TITLE_CODE = T.TITLE_CODE
			WHERE 1 = 1
			-- AND E.PAY_CLASS <> 'S'
		) A
	) B
	GROUP BY 1, 2, 3, 4, 5, 6
) X
